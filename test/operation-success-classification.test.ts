const providerFailClosed = new Map([
    ['AdminAllergensController_upload', 'object storage and malware scanner'],
    ['AdminReviewController_prepareExport', 'protected export storage'],
    ['AiController_purchase', 'payment adapter'],
    ['DiaryController_uploadMedia', 'object storage, KMS and malware scanner'],
    ['ExportsController_download', 'protected export storage'],
]);

const externalSuccessRequired = new Map([
    ['AiController_preview', 'AI provider'],
    ['AiController_run', 'AI provider reserve/finalize/refund'],
    ['AiController_continueTask', 'AI provider reserve/finalize/refund'],
]);

void test('every OpenAPI operation has an honest success/effect acceptance classification', () => {
    const document = JSON.parse(
        readFileSync(new URL('../../contracts/openapi.json', import.meta.url), 'utf8'),
    ) as OpenApi;
    const operations = Object.values(document.paths)
        .flatMap((pathItem) => Object.values(pathItem))
        .filter((operation): operation is Operation & { operationId: string } => Boolean(operation?.operationId));
    const ids = new Set(operations.map((operation) => operation.operationId));
    assert.equal(ids.size, 351);
    assert.equal(operations.length, ids.size, 'operationId values must remain unique');

    for (const id of explicitLiveSuccess) assert.ok(ids.has(id), `${id}: explicit live-success operation is absent`);
    for (const [id, reason] of [...providerFailClosed, ...externalSuccessRequired]) {
        assert.ok(ids.has(id), `${id}: provider-classified operation is absent`);
        assert.ok(reason.length >= 10, `${id}: provider classification needs a concrete reason`);
    }
    const exceptional = [...explicitLiveSuccess, ...providerFailClosed.keys(), ...externalSuccessRequired.keys()];
    assert.equal(new Set(exceptional).size, exceptional.length, 'acceptance categories must not overlap');

    const pending = operations.filter(
        ({ operationId }) =>
            !explicitLiveSuccess.has(operationId) &&
            !providerFailClosed.has(operationId) &&
            !externalSuccessRequired.has(operationId),
    );
    const pendingByTag = Object.fromEntries(
        [...new Set(pending.map((operation) => operation.tags?.[0] ?? 'untagged'))]
            .sort()
            .map((tag) => [tag, pending.filter((operation) => (operation.tags?.[0] ?? 'untagged') === tag).length]),
    );

    assert.equal(explicitLiveSuccess.size, 343);
    assert.equal(providerFailClosed.size, 5);
    assert.equal(externalSuccessRequired.size, 3);
    assert.equal(pending.length, 0);
    assert.deepEqual(pendingByTag, {});
});
